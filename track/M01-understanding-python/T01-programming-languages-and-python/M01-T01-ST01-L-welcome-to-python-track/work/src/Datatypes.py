#int
a=10
print(type(a),a)

#float
b=65.21 # pos n negative values do not affect the datatype
print(type(b),b)

#boolean
c=True
print(type(c),c)

#str
d="HELLO"
print(type(d),d)

#list
e=[1,2,3]
print(type(e),e)

#tuple
f=(1,2,3)
print(type(f),f)

#dictionary
g={a:"apple" , b:"bat"}
print(type(g),g)

#set
h={1,2,3}
print(type(h),h)

#complex
i = 3+6j
print(type(i),i)

#none
is_valid=None
print(type(is_valid),is_valid)

